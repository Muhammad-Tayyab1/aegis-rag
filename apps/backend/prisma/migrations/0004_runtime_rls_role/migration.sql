DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'aegis_runtime') THEN
    CREATE ROLE aegis_runtime NOLOGIN;
  END IF;
END
$$;

GRANT aegis_runtime TO CURRENT_USER;
GRANT USAGE ON SCHEMA public TO aegis_runtime;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO aegis_runtime;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO aegis_runtime;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO aegis_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO aegis_runtime;
